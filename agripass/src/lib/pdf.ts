import { jsPDF } from 'jspdf';
import type { CountryProfile, DocSpec, Commodity } from '../data/types';
import type { DocState } from './docstate';

// jsPDF core fonts are WinAnsi: map common Unicode to safe equivalents.
const MAP: Record<string, string> = {
  '‘': "'", '’': "'", '“': '"', '”': '"', '–': '-', '—': '-', '…': '...', '≤': '<=', '≥': '>=',
  '×': 'x', '₂': '2', '₃': '3', '₅': '5', '⁰': '0', '¹': '1', '⁻': '-', '⁵': '5', '⁶': '6', '⁷': '7',
  '⁸': '8', '⁹': '9', '⁴': '4', '→': '->', '·': '-', '•': '-', '™': '(TM)', ' ': ' ', ' ': ' ', '‑': '-',
  '₀': '0', '₁': '1', '₄': '4', '±': '+/-',
};
export const pdfText = (s: string) => [...(s ?? '')].map((ch) => MAP[ch] ?? (ch.charCodeAt(0) > 255 ? '?' : ch)).join('');

const INK: [number, number, number] = [23, 33, 28];
const MUTED: [number, number, number] = [91, 106, 97];
const BRAND: [number, number, number] = [31, 92, 69];
const LINE: [number, number, number] = [200, 206, 196];
const TINT: [number, number, number] = [236, 239, 231];

export interface PdfCtx { country: CountryProfile; commodity?: Commodity; generatedAt: Date; draftId: (d: DocSpec) => string }

const W = 210, H = 297, MX = 14;

function watermark(pdf: jsPDF) {
  const g = (pdf as unknown as { GState: new (o: object) => unknown }).GState;
  pdf.saveGraphicsState();
  try { pdf.setGState(new g({ opacity: 0.07 }) as never); } catch { /* older viewers */ }
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(38);
  pdf.setTextColor(...BRAND);
  pdf.text('DRAFT - NOT AN OFFICIAL CERTIFICATE', W / 2, H / 2 + 20, { align: 'center', angle: 35 });
  pdf.restoreGraphicsState();
}

function footer(pdf: jsPDF, doc: DocSpec, ctx: PdfCtx, page: number) {
  pdf.setDrawColor(...LINE);
  pdf.line(MX, H - 19, W - MX, H - 19);
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(6.8);
  pdf.setTextColor(...MUTED);
  const left = pdfText(`Pre-filled application draft generated by AgriPass Global on ${ctx.generatedAt.toLocaleString('en-IN')}. Not valid for customs or plant-health clearance until issued and signed by the competent authority.`);
  pdf.text(pdf.splitTextToSize(left, 140), MX, H - 15.5);
  pdf.text(`${ctx.draftId(doc)}  |  p.${page}`, W - MX, H - 15.5, { align: 'right' });
}

function header(pdf: jsPDF, doc: DocSpec, ctx: PdfCtx): number {
  // guilloche-like double frame
  pdf.setDrawColor(...BRAND);
  pdf.setLineWidth(0.6);
  pdf.rect(8, 8, W - 16, H - 16);
  pdf.setLineWidth(0.2);
  pdf.rect(9.6, 9.6, W - 19.2, H - 19.2);

  pdf.setFillColor(...BRAND);
  pdf.rect(MX, 14, W - 2 * MX, 24, 'F');
  pdf.setTextColor(255, 255, 255);
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(7.2);
  const iss = pdf.splitTextToSize(pdfText(`ISSUING / RECEIVING AUTHORITY: ${doc.issuer.toUpperCase()}`), 128);
  pdf.text(iss.slice(0, 2), MX + 4, 19.5);
  pdf.setFont('times', 'bold');
  pdf.setFontSize(15);
  pdf.text(pdf.splitTextToSize(pdfText(doc.title.toUpperCase()), 130).slice(0, 2), MX + 4, 29.5);
  // draft stamp
  pdf.setDrawColor(255, 255, 255);
  pdf.setLineWidth(0.4);
  pdf.roundedRect(W - MX - 46, 17, 42, 18, 1.5, 1.5);
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(10);
  pdf.text('DRAFT', W - MX - 25, 23.5, { align: 'center' });
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(6.5);
  pdf.text(pdfText(ctx.draftId(doc)), W - MX - 25, 28, { align: 'center' });
  pdf.text(pdfText(`${doc.requirement.toUpperCase()} - ${ctx.country.name}`), W - MX - 25, 32, { align: 'center' });

  pdf.setTextColor(...MUTED);
  pdf.setFontSize(7.4);
  const sub = pdfText(`Destination: ${ctx.country.name}  |  Legal basis: ${doc.legal ?? '-'}  |  ${doc.portal ? 'Portal: ' + doc.portal : 'Lead time: ' + doc.leadTime}`);
  pdf.text(pdf.splitTextToSize(sub, W - 2 * MX), MX, 43);
  return 49;
}

export function drawDoc(pdf: jsPDF, doc: DocSpec, st: DocState, ctx: PdfCtx, first: boolean) {
  if (!first) pdf.addPage();
  let page = 1;
  let y = header(pdf, doc, ctx);
  watermark(pdf);
  const colW = (W - 2 * MX - 4) / 2;
  let box = 1;

  const ensure = (h: number) => {
    if (y + h > H - 23) {
      footer(pdf, doc, ctx, page);
      pdf.addPage();
      page++;
      pdf.setDrawColor(...BRAND); pdf.setLineWidth(0.6); pdf.rect(8, 8, W - 16, H - 16);
      watermark(pdf);
      pdf.setFont('helvetica', 'bold'); pdf.setFontSize(8); pdf.setTextColor(...MUTED);
      pdf.text(pdfText(`${doc.title} (continued)`), MX, 16);
      y = 22;
    }
  };

  const sections = [...new Set(st.fields.map((f) => f.section))];
  for (const sec of sections) {
    ensure(28);
    pdf.setFillColor(...TINT);
    pdf.rect(MX, y, W - 2 * MX, 6, 'F');
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(8);
    pdf.setTextColor(...BRAND);
    pdf.text(pdfText(sec.toUpperCase()), MX + 2, y + 4.1);
    y += 8;
    const fs = st.fields.filter((f) => f.section === sec);
    let col = 0;
    let rowH = 0;
    for (const f of fs) {
      const full = f.def.full || (f.value ?? '').length > 70;
      const w = full ? W - 2 * MX : colW;
      if (full && col === 1) { y += rowH + 2; col = 0; rowH = 0; }
      const x = col === 0 ? MX : MX + colW + 4;
      const val = f.def.type === 'checkbox' ? (f.value === 'true' || f.value === 'Yes' ? '[X] Confirmed' : '[  ] Not confirmed') : f.value || '';
      pdf.setFont('helvetica', 'normal');
      pdf.setFontSize(9);
      const lines = pdf.splitTextToSize(pdfText(val + (f.def.unit && val ? ` ${f.def.unit}` : '')), w - 4);
      const h = Math.max(11, 7 + lines.length * 3.9);
      ensure(h + 2);
      pdf.setDrawColor(...LINE);
      pdf.setLineWidth(0.25);
      pdf.rect(x, y, w, h);
      pdf.setFontSize(6.4);
      pdf.setTextColor(...MUTED);
      const tag = f.kind === 'manual' ? '' : ' (master)';
      pdf.text(pdfText(`${box}. ${f.def.label}${tag}`).slice(0, 110), x + 1.6, y + 3.4);
      pdf.setFontSize(9);
      pdf.setTextColor(...(val ? INK : MUTED));
      if (!val) {
        pdf.setFont('helvetica', 'italic');
        pdf.text(f.def.required ? 'Required - not yet completed' : '-', x + 1.6, y + 7.8);
      } else pdf.text(lines, x + 1.6, y + 7.8);
      box++;
      rowH = Math.max(rowH, h);
      if (full) { y += h + 2; col = 0; rowH = 0; }
      else if (col === 0) col = 1;
      else { y += rowH + 2; col = 0; rowH = 0; }
    }
    if (col === 1) { y += rowH + 2; }
    y += 2;
  }
  // signature / seal block
  ensure(26);
  pdf.setDrawColor(...LINE);
  pdf.setLineWidth(0.25);
  pdf.rect(MX, y, colW, 22);
  pdf.rect(MX + colW + 4, y, colW, 22);
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(6.4);
  pdf.setTextColor(...MUTED);
  const signer = doc.side === 'exporter' ? 'Authorized signatory (exporter) - name, designation, date' : 'To be signed by the issuing officer - name, designation, date';
  pdf.text(pdfText(signer), MX + 1.6, y + 3.4);
  pdf.text(pdfText(doc.side === 'exporter' ? 'Company stamp' : 'Official seal of the issuing authority (applied on issuance)'), MX + colW + 5.6, y + 3.4);
  y += 26;
  pdf.setFontSize(7);
  pdf.setTextColor(...MUTED);
  const comp = pdfText(`Completion: ${st.pct}% (${st.filled}/${st.required} required fields)${st.errors.length ? ` - ${st.errors.length} issue(s) open` : ''}. Requirement basis: ${doc.reason} Source: ${doc.source?.label ?? '-'}`);
  ensure(12);
  pdf.text(pdf.splitTextToSize(comp, W - 2 * MX), MX, y);
  footer(pdf, doc, ctx, page);
}

export function docPdf(doc: DocSpec, st: DocState, ctx: PdfCtx): jsPDF {
  const pdf = new jsPDF({ unit: 'mm', format: 'a4' });
  pdf.setProperties({ title: pdfText(`${doc.title} - DRAFT`), subject: 'AgriPass Global pre-filled draft', creator: 'AgriPass Global' });
  drawDoc(pdf, doc, st, ctx, true);
  return pdf;
}

export interface CoverInfo { rows: [string, string][]; checklist: { title: string; req: string; status: string; pct: number; issuer: string }[]; pathway: string[] }

export function packPdf(docs: { doc: DocSpec; st: DocState }[], ctx: PdfCtx, cover: CoverInfo): jsPDF {
  const pdf = new jsPDF({ unit: 'mm', format: 'a4' });
  pdf.setProperties({ title: pdfText(`Export Compliance Dossier - ${ctx.country.name}`), creator: 'AgriPass Global' });
  pdf.setDrawColor(...BRAND); pdf.setLineWidth(0.6); pdf.rect(8, 8, W - 16, H - 16);
  pdf.setFillColor(...BRAND); pdf.rect(MX, 14, W - 2 * MX, 30, 'F');
  pdf.setTextColor(255, 255, 255);
  pdf.setFont('helvetica', 'normal'); pdf.setFontSize(8);
  pdf.text('AGRIPASS GLOBAL  |  SINGLE-WINDOW EXPORT DOCUMENT PACK', MX + 4, 21);
  pdf.setFont('times', 'bold'); pdf.setFontSize(20);
  pdf.text(pdfText(`India -> ${ctx.country.name}`), MX + 4, 32);
  pdf.setFont('helvetica', 'normal'); pdf.setFontSize(9);
  pdf.text(pdfText(ctx.commodity ? `${ctx.commodity.name} - HS ${ctx.commodity.hs}` : ''), MX + 4, 39);
  let y = 52;
  pdf.setTextColor(...INK);
  pdf.setFontSize(8.5);
  for (const [k, v] of cover.rows) {
    pdf.setTextColor(...MUTED); pdf.text(pdfText(k), MX, y);
    pdf.setTextColor(...INK); pdf.text(pdf.splitTextToSize(pdfText(v || '-'), 130), MX + 46, y);
    y += 5.2;
  }
  y += 3;
  pdf.setFont('helvetica', 'bold'); pdf.setFontSize(9); pdf.setTextColor(...BRAND);
  pdf.text('HARMONIZED REGULATORY PATHWAY', MX, y); y += 5;
  pdf.setFont('helvetica', 'normal'); pdf.setFontSize(7.6); pdf.setTextColor(...INK);
  for (const p of cover.pathway) { const l = pdf.splitTextToSize(pdfText('- ' + p), W - 2 * MX); pdf.text(l, MX, y); y += l.length * 3.6 + 1; }
  y += 3;
  pdf.setFont('helvetica', 'bold'); pdf.setFontSize(9); pdf.setTextColor(...BRAND);
  pdf.text('DOCUMENT CHECKLIST', MX, y); y += 2;
  pdf.setFontSize(7); pdf.setTextColor(...MUTED);
  const cols = [MX, MX + 84, MX + 106, MX + 136];
  y += 4;
  ['Document', 'Requirement', 'Status', 'Issuer'].forEach((h, i) => pdf.text(h, cols[i], y));
  y += 1.5; pdf.setDrawColor(...LINE); pdf.line(MX, y, W - MX, y); y += 3.8;
  pdf.setFont('helvetica', 'normal'); pdf.setTextColor(...INK);
  for (const c of cover.checklist) {
    if (y > H - 30) { pdf.addPage(); pdf.setDrawColor(...BRAND); pdf.setLineWidth(0.6); pdf.rect(8, 8, W - 16, H - 16); y = 20; }
    const t = pdf.splitTextToSize(pdfText(c.title), 80);
    pdf.text(t, cols[0], y); pdf.text(c.req, cols[1], y); pdf.text(`${c.status} (${c.pct}%)`, cols[2], y);
    pdf.text(pdf.splitTextToSize(pdfText(c.issuer), W - MX - cols[3]).slice(0, 2), cols[3], y);
    y += Math.max(t.length, 2) * 3.4 + 1.2;
  }
  pdf.setFontSize(6.8); pdf.setTextColor(...MUTED);
  pdf.text(pdf.splitTextToSize(pdfText('All pages are pre-filled drafts for application and internal review. Requirements are drawn from USDA FAIRS reports (via APEDA AgriExchange) and published regulations; confirm with the competent authorities and your importer before shipment.'), W - 2 * MX), MX, H - 16);
  docs.forEach(({ doc, st }) => drawDoc(pdf, doc, st, ctx, false));
  return pdf;
}
